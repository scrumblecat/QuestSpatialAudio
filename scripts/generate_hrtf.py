"""Reproduce the embedded 44.1/48 kHz MIT KEMAR diffuse-field HRIRs.

Only Python's standard library is required. Download the upstream archive
separately and pass --archive; see assets/hrtf/NOTICE.md. No audio recordings
from the game are used. Positive azimuth is to the listener's right.
"""
from pathlib import Path
import argparse
import hashlib
import io
import math
import re
import struct
import wave
import zipfile

ROOT = Path(__file__).resolve().parents[1]
ARCHIVE_SHA256 = "a48e73137390626ef1e45d1de6a4d98530c6aa570e71b40f7c4442241ed5fa22"


def resample(samples, rate):
    ratio = rate / 44100
    result = []
    for i in range(math.ceil(len(samples) * ratio)):
        x = i / ratio
        total = 0.0
        for j in range(max(0, math.ceil(x - 16)), min(len(samples), math.floor(x + 16) + 1)):
            d = x - j
            sinc = 1.0 if abs(d) < 1e-9 else math.sin(math.pi * d) / (math.pi * d)
            window = 0.5 + 0.5 * math.cos(math.pi * d / 16)
            total += samples[j] * sinc * window
        # Preserve the transfer-function gain when resampling an impulse response.
        result.append(max(-32768, min(32767, round(total / ratio))))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--archive', type=Path, required=True,
                        help='Path to the separately downloaded MIT KEMAR diffuse.zip')
    args = parser.parse_args()
    archive_bytes = args.archive.read_bytes()
    if hashlib.sha256(archive_bytes).hexdigest() != ARCHIVE_SHA256:
        raise ValueError('The archive does not match the expected upstream SHA-256.')
    responses = []
    with zipfile.ZipFile(io.BytesIO(archive_bytes)) as archive:
        for name in archive.namelist():
            match = re.search(r"H(-?\d+)e(\d+)a\.wav$", name, re.I)
            if not match:
                continue
            elevation, azimuth = map(int, match.groups())
            with wave.open(io.BytesIO(archive.read(name))) as wav:
                assert (wav.getnchannels(), wav.getsampwidth(), wav.getframerate(), wav.getnframes()) == (2, 2, 44100, 128)
                samples = struct.unpack("<256h", wav.readframes(128))
            responses.append((elevation, azimuth, samples[::2], samples[1::2]))
    responses.sort(key=lambda row: row[:2])
    assert len(responses) == 368
    out = [
        '// Generated by scripts/generate_hrtf.py; do not edit.',
        '// MIT Media Laboratory, Copyright 1994. Bill Gardner and Keith Martin.',
        '// See assets/hrtf/NOTICE.md for citation and usage terms.',
        f'// Archive SHA-256: {ARCHIVE_SHA256}',
        '#include "qsa/hrtf_data.hpp"',
        'namespace qsa {',
        'const HrtfResponse kHrtfResponses[kResponseCount] = {'
    ]
    for el, az, left, right in responses:
        e, a = math.radians(el), math.radians(az)
        vector = [math.cos(e) * math.sin(a), math.sin(e), math.cos(e) * math.cos(a)]
        vec = ', '.join(f'{v:.9f}f' for v in vector)
        out.append(f'  {{{{{vec}}}, // elevation {el}, azimuth {az}')
        for channel in (left, right):
            out.append('    {' + ','.join(map(str, channel)) + '},')
        for channel in (left, right):
            out.append('    {' + ','.join(map(str, resample(channel, 48000))) + '},')
        out.append('  },')
    out.extend(['};', '}'])
    dest = ROOT / 'src/hrtf_data.cpp'
    dest.parent.mkdir(exist_ok=True)
    dest.write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'Generated {len(responses)} HRIR pairs: {dest}')


if __name__ == '__main__':
    main()
